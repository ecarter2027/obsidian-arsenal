package com.obsidianarsenal.client.mesh;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import com.obsidianarsenal.ObsidianArsenal;
import net.minecraft.client.Minecraft;
import net.minecraft.client.renderer.LightTexture;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.phys.Vec3;
import software.bernie.geckolib.cache.object.GeoBone;
import software.bernie.geckolib.core.animatable.GeoAnimatable;
import software.bernie.geckolib.renderer.GeoRenderer;
import software.bernie.geckolib.renderer.layer.GeoRenderLayer;

import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * Draws smooth parts (thorns, bands, capsules, rounded plates) on top of a GeckoLib model, attached to its bones so
 * they follow every bone animation and the armor's slot visibility. Parts are read from
 * assets/obsidian_arsenal/smooth/<name>.json (generated by tools/gen_assets.py) in Blockbench pixel coordinates.
 */
public class SmoothPartsLayer<T extends GeoAnimatable> extends GeoRenderLayer<T> {
    public static final ResourceLocation OBSIDIAN = ObsidianArsenal.id("textures/entity/smooth_obsidian.png");
    public static final ResourceLocation GLOW = ObsidianArsenal.id("textures/entity/smooth_glow.png");

    private record Part(String type, String mat, double[] a, double[] b, double[] c, double len, double r, double r2, double p, double glow) {}

    private final ResourceLocation spec;
    private Map<String, List<Part>> parts;

    public SmoothPartsLayer(GeoRenderer<T> renderer, String name) {
        super(renderer);
        this.spec = ObsidianArsenal.id("smooth/" + name + ".json");
    }

    private Map<String, List<Part>> parts() {
        if (parts != null) return parts;
        Map<String, List<Part>> out = new HashMap<>();
        try {
            var res = Minecraft.getInstance().getResourceManager().getResource(spec);
            if (res.isPresent()) try (Reader rd = new InputStreamReader(res.get().open(), StandardCharsets.UTF_8)) {
                JsonObject root = JsonParser.parseReader(rd).getAsJsonObject();
                for (var e : root.entrySet()) {
                    List<Part> list = new ArrayList<>();
                    for (JsonElement pe : e.getValue().getAsJsonArray()) {
                        JsonObject o = pe.getAsJsonObject();
                        list.add(new Part(o.get("type").getAsString(), o.has("mat") ? o.get("mat").getAsString() : "obsidian",
                                vec(o, "a"), vec(o, "b"), vec(o, "c"), num(o, "len"), num(o, "r"), num(o, "r2"), num(o, "p"), num(o, "glow")));
                    }
                    out.put(e.getKey(), list);
                }
            }
        } catch (Exception ex) {
            ObsidianArsenal.LOGGER.error("Could not read smooth parts {}", spec, ex);
        }
        return parts = out;
    }

    private static double[] vec(JsonObject o, String k) {
        if (!o.has(k)) return new double[]{0, 0, 0};
        JsonArray a = o.getAsJsonArray(k);
        return new double[]{a.get(0).getAsDouble(), a.get(1).getAsDouble(), a.get(2).getAsDouble()};
    }

    private static double num(JsonObject o, String k) { return o.has(k) ? o.get(k).getAsDouble() : 0; }

    /** Blockbench pixels -> GeckoLib model space (blocks, x mirrored like baked cubes). */
    private static Vec3 pos(double[] v) { return new Vec3(-v[0] / 16.0, v[1] / 16.0, v[2] / 16.0); }
    private static Vec3 dir(double[] v) { return new Vec3(-v[0], v[1], v[2]); }

    @Override
    public void renderForBone(PoseStack poseStack, T animatable, GeoBone bone, RenderType renderType, MultiBufferSource bufferSource,
                              VertexConsumer buffer, float partialTick, int packedLight, int packedOverlay) {
        if (bone.isHidden()) return;
        List<Part> list = parts().get(bone.getName());
        if (list == null || list.isEmpty()) return;
        PoseStack.Pose pose = poseStack.last();
        Mesh.Out body = new Mesh.Out(bufferSource.getBuffer(RenderType.entityCutoutNoCull(OBSIDIAN)), packedLight, packedOverlay, 1, 1, 1, 1);
        // glowing parts go in a second pass so the two buffers never interleave
        List<Part> glowing = new ArrayList<>();
        for (Part p : list) {
            if (p.mat().equals("glow")) { glowing.add(p); continue; }
            draw(p, body, null, pose);
        }
        Mesh.Out glow = new Mesh.Out(bufferSource.getBuffer(RenderType.entityTranslucentEmissive(GLOW)), LightTexture.FULL_BRIGHT, packedOverlay, 1, 1, 1, 1);
        for (Part p : list) if (p.type().equals("thorn") && p.glow() > 0) drawThornTip(p, glow, pose);
        for (Part p : glowing) draw(p, glow, null, pose);
        bufferSource.getBuffer(renderType);   // hand the shared buffer back to GeckoLib in its own render type
    }

    private static void draw(Part p, Mesh.Out o, Mesh.Out glow, PoseStack.Pose pose) {
        switch (p.type()) {
            case "thorn" -> Mesh.thorn(o, null, pose, pos(p.a()), dir(p.b()), p.len() / 16.0, p.r() / 16.0,
                    dir(p.c()).scale(1 / 16.0), 0);
            case "tube" -> Mesh.tube(o, pose, pos(p.a()), dir(p.b()), p.len() / 16.0, p.r() / 16.0, (p.r2() > 0 ? p.r2() : p.r()) / 16.0, p.p() > 0 ? p.p() : 1);
            case "capsule" -> Mesh.capsule(o, pose, pos(p.a()), pos(p.b()), p.r() / 16.0);
            case "blob" -> Mesh.blob(o, pose, pos(p.a()), new Vec3(p.b()[0], p.b()[1], p.b()[2]).scale(1 / 16.0), p.p() > 0 ? p.p() : 2);
            default -> {}
        }
    }

    /** Re-draws the tip of a thorn, slightly proud of the body, in the glow material. */
    private static void drawThornTip(Part p, Mesh.Out glow, PoseStack.Pose pose) {
        double f = Math.min(0.9, p.glow());
        double len = p.len() / 16.0, t0 = 1 - f;
        Vec3 base = pos(p.a()), d = dir(p.b()).normalize(), bend = dir(p.c()).scale(1 / 16.0);
        Vec3 start = base.add(d.scale(len * t0)).add(bend.scale(t0 * t0));
        Vec3 tan = d.scale(len).add(bend.scale(2 * t0));
        double r0 = p.r() / 16.0 * Math.pow(1 - t0, 1.35) * 1.06;
        Mesh.thorn(glow, null, pose, start, tan, len * f * 1.01, r0, bend.scale(f * f), 0);
    }
}
